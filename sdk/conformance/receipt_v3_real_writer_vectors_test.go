// Update with go test ./sdk/conformance -run TestReceiptV3RealWriterVectors -args -update-receipt-v3.
// Recorder timestamps and group IDs are generated by the writers, so updated bytes change.
func TestReceiptV3RealWriterVectors(t *testing.T) {
	for _, name := range []string{"writer-legacy-appended", "writer-legacy-switched", "writer-group-switched"} {
		t.Run("g09-"+name, func(t *testing.T) {
			if !*updateReceiptV3 {
				v3RunFrozenWriterRecipe(t, 9, name)
				return
			}
			dir := t.TempDir()
			key := v3Key("first")
			pub := v3Public(key)
			options := v3.StreamWriterOptions{
				Dir: dir, SigningKey: key, Random: bytes.NewReader(bytes.Repeat([]byte{0x11}, 64)),
				Clock:    func() time.Time { return time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC) },
				Identity: v3.Writer{Instance: "example", Product: "Pipelock", Version: "3"}, PolicyHash: v3.Digest(nil),
				Coverage:        v3.Coverage{ReceiptsRequired: true, Surfaces: []string{"fetch"}, RedactionRuleset: v3.Ruleset{Hash: v3.Digest(nil), ID: "example", Version: "1"}},
				PriorSignerKeys: []ed25519.PublicKey{pub},
			}
			writeV3 := func() {
				w, err := v3.OpenStreamWriter(t.Context(), options)
				if err != nil {
					t.Fatal(err)
				}
				v3WriteCorpusAction(t, w)
				if err := w.Close(t.Context(), nil); err != nil {
					t.Fatal(err)
				}
			}
			writeOld := func(group bool) {
				rec, err := recorder.New(recorder.Config{Enabled: true, Dir: dir, SignCheckpoints: true}, nil, key)
				if err != nil {
					t.Fatal(err)
				}
				config := actionreceipt.EmitterConfig{Recorder: rec, PrivKey: key, ConfigHash: v3.Digest(nil), Principal: "example", Actor: "example", Session: "proxy"}
				if group {
					set, err := actionreceipt.OpenInitialReceiptShardSet(config, "proxy", 2, 0)
					if err != nil {
						t.Fatal(err)
					}
					for _, emitter := range set.Emitters() {
						if err := emitter.EmitSessionClose("graceful_shutdown"); err != nil {
							t.Fatal(err)
						}
						if err := emitter.EmitTranscriptRoot(emitter.Session()); err != nil {
							t.Fatal(err)
						}

					}
					if _, err := set.PublishClose(); err != nil {
						t.Fatal(err)
					}
				} else {
					emitter := actionreceipt.NewEmitter(config)
					if err := emitter.EmitSessionOpen(); err != nil {
						t.Fatal(err)
					}
					if err := emitter.EmitSessionClose("graceful_shutdown"); err != nil {
						t.Fatal(err)
					}
				}
				if err := rec.Close(); err != nil {
					t.Fatal(err)
				}
			}
			switch name {
			case "writer-legacy-appended":
				writeV3()
				v3WriteOldBinaryEvidence(t, dir, key)
			case "writer-legacy-switched":
				v3WriteOldBinaryEvidence(t, dir, key)
				writeV3()
			default:
				writeOld(true)
				writeV3()
			}
			request := v3Request{Directory: true, Keys: []string{hex.EncodeToString(pub)}, AllowPrefix: true}
			opts := v3.Options{Directory: true, Keys: []ed25519.PublicKey{pub}, AllowPrefix: true}
			result, err := v3.VerifyPaths(t.Context(), []string{dir}, opts)
			if err != nil {
				t.Fatal(err)
			}
			recipe := v3Recipe{group: 9, name: name, verdict: result.Verdict, request: request, files: v3ReadWrittenCorpus(t, dir)}
			for _, f := range result.Findings {
				if f.Class == "invalid" {
					if recipe.code == "" {
						recipe.code = f.Code
					} else {
						recipe.extraInvalid = append(recipe.extraInvalid, f.Code)
					}
				}
			}
			t.Logf("%s full verdict: %s", name, result.Verdict)
			if result.Verdict == "" {
				t.Fatal(fmt.Errorf("writer produced no verdict"))
			}
			v3RunRecipe(t, recipe)
		})
	}
}

// The older executable lacks the later directory-switch guard. It runs only
// against this test's temporary evidence directory and local stdio child.
func v3WriteOldBinaryEvidence(t *testing.T, dir string, key ed25519.PrivateKey) {
	t.Helper()
	bin, err := exec.LookPath("pipelock")
	if err != nil {
		t.Fatal(err)
	}
	version, err := exec.CommandContext(t.Context(), bin, "version").Output() // #nosec G204 -- opt-in fixture generator uses the pinned binary.
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(version), "3024edf44987") {
		t.Fatal("fixture generation requires the pinned v3.8.0-rc.20261026.3024edf44987 binary")
	}
	scratch := t.TempDir()
	keyPath := filepath.Join(scratch, "signing.key")
	if err := signing.SavePrivateKey(key, keyPath); err != nil {
		t.Fatal(err)
	}
	config := fmt.Sprintf("mode: balanced\nflight_recorder:\n  enabled: true\n  dir: %q\n  signing_key_path: %q\n  sign_checkpoints: true\n", dir, keyPath)
	configPath := filepath.Join(scratch, "pipelock.yaml")
	if err := os.WriteFile(configPath, []byte(config), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.CommandContext(t.Context(), bin, "--home", filepath.Join(scratch, "home"), "mcp", "proxy", "--config", configPath, "--", "cat") // #nosec G204 -- fixed arguments and a temporary fixture directory.
	cmd.Stdin = strings.NewReader("{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"tools/call\",\"params\":{\"name\":\"example\",\"arguments\":{}}}\n")
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("older writer: %v: %s", err, output)
	}
}
