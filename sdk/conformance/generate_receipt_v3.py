"""Render the receipt v3 field registry as Go, JSON Schema and Markdown."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SDK = ROOT / "sdk/receipt-v3"
SPEC = ROOT / "docs/specs/receipt-v3.md"
START = "<!-- BEGIN generated receipt v3 registry -->"
END = "<!-- END generated receipt v3 registry -->"
REG = json.loads((SDK / "registry.json").read_text())
OBJECTS = REG["objects"]
LIMITS = REG["limits"]
INT_MAX = LIMITS["integer"]

STRINGS = {
    "string": {},
    "name": {"pattern": "^[a-z][a-z0-9_]{0,63}$"},
    "id128": {"pattern": "^[0-9a-f]{32}$"},
    "action_id": {"pattern": "^[A-Za-z0-9._:-]{1,128}$"},
    "digest": {"pattern": "^sha256:[0-9a-f]{64}$"},
    "key": {"pattern": "^[A-Za-z0-9+/]{42}[AEIMQUYcgkosw048]=$"},
    "time": {
        "format": "date-time",
        "pattern": "^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\\.[0-9]{3}Z$",
    },
    "target": {"maxLength": LIMITS["target_bytes"], "x-pipelock-maxBytes": LIMITS["target_bytes"],
                 "description": "Enforce x-pipelock-maxBytes separately on the UTF-8 encoding."},
    "instance": {"maxLength": LIMITS["writer_instance_bytes"], "x-pipelock-maxBytes": LIMITS["writer_instance_bytes"],
                 "description": "Enforce x-pipelock-maxBytes separately on the UTF-8 encoding."},
}
INTEGERS = {"uint": 0, "positive": 1, "version": 3}
INITIALISMS = {
    "id": "ID", "fsync": "Fsync", "ts": "TS", "v": "V",
    "uid": "UID", "url": "URL", "svg": "SVG", "sha256": "SHA256",
}


def title(name):
    return "".join(INITIALISMS.get(part, part.title()) for part in name.split("_"))


def schema(kind, required):
    if kind.startswith("[]"):
        return {"type": "array", "minItems": int(not required), "items": schema(kind[2:], True)}
    if kind.startswith("@"):
        return {"type": "string", "enum": REG["enums"][kind[1:]]}
    if kind in STRINGS:
        return {"type": "string", "minLength": 1, **STRINGS[kind]}
    if kind in INTEGERS:
        return {"type": "integer", "minimum": INTEGERS[kind], "maximum": 3 if kind == "version" else INT_MAX}
    if kind == "bool":
        return {"type": "boolean"}
    if kind == "object":
        return {"type": "object", "minProperties": int(not required)}
    if kind in OBJECTS:
        return {"$ref": f"#/$defs/{kind}"}
    raise ValueError(kind)


def object_schema(name):
    fields = OBJECTS[name]
    result = {"type": "object", "additionalProperties": False, "minProperties": 1,
              "properties": {key: schema(field["type"], field["required"]) for key, field in fields.items()}}
    if name == "Coverage":
        result["properties"]["surfaces"]["description"] = (
            "Check separately that entries are in nondecreasing UTF-8 byte order. "
            "Empty arrays and repeated entries are allowed."
        )
    required = [key for key, field in fields.items() if field["required"]]
    if required:
        result["required"] = required
    conditions = []
    for condition in REG["conditions"].get(name, []):
        then = {}
        if condition.get("require"):
            then["required"] = condition["require"]
        if condition.get("forbid"):
            then["not"] = {"anyOf": [{"required": [key]} for key in condition["forbid"]]}
        if condition.get("equals"):
            then["properties"] = {key: {"const": value} for key, value in condition["equals"].items()}
        conditions.append({
            "if": {
                "required": [condition["field"]],
                "properties": {condition["field"]: {"const": condition["value"]}},
            },
            "then": then,
        })
    if conditions:
        result["allOf"] = conditions
    if name == "StreamOpen":
        result["oneOf"] = [{"required": [field]} for field in ("previous", "legacy_cutover")]
    return result


def nested(name):
    yield name
    for field in OBJECTS[name].values():
        kind = field["type"].removeprefix("[]")
        if kind in OBJECTS:
            yield from nested(kind)


def go_type(kind, required):
    if kind.startswith("[]"):
        return "[]" + go_type(kind[2:], True)
    if kind in STRINGS or kind.startswith("@"):
        return "string"
    if kind == "object":
        return "json.RawMessage"
    if kind in INTEGERS or kind == "bool":
        value = "int64" if kind in INTEGERS else "bool"
        return value if required else "*" + value
    if kind in OBJECTS:
        return kind if required else "*" + kind
    raise ValueError(kind)


def go_source():
    lines = [
        "// Copyright 2026 Pipelab", "// SPDX-License-Identifier: Apache-2.0", "",
        "// Code generated by generate_receipt_v3.py; DO NOT EDIT.", "", "package v3",
        'import "encoding/json"', "", "const (", f'PayloadType = {json.dumps(REG["profile"])}',
    ]
    for key, value in REG["layout"].items():
        lines.append(f"layout{title(key)} = {json.dumps(value)}")
    for key, value in LIMITS.items():
        lines.append(f"max{title(key)} = {value}")
    for kind in REG["kinds"]:
        lines.append(f'kind{title(kind)} = "{kind}"')
    for code in REG["findings"]:
        lines.append(f'code{title(code.lower())} = "{code}"')
    lines.extend((")", "", "var findingClasses = map[string]string{"))
    for code, cls in REG["findings"].items():
        lines.append(f'code{title(code.lower())}: "{cls}",')
    lines.extend(("}", "", "type fieldSpec struct { kind string; required bool }",
                  "var wireFields = map[string]map[string]fieldSpec{"))
    for name, fields in OBJECTS.items():
        lines.append(f'"{name}": {{')
        for key, field in fields.items():
            lines.append(f'"{key}": {{{json.dumps(field["type"])}, {str(field["required"]).lower()}}},')
        lines.append("},")
    lines.extend(("}", "", "var wireEnums = map[string][]string{"))
    for name, values in REG["enums"].items():
        lines.append(f'"{name}": {{' + ", ".join(map(json.dumps, values)) + "},")
    lines.extend(("}", "", "type conditionalSpec struct { field, value string; require, forbid []string; equals map[string]any }",
                  "var wireConditions = map[string][]conditionalSpec{"))
    for name, conditions in REG["conditions"].items():
        lines.append(f'"{name}": {{')
        for condition in conditions:
            parts = [json.dumps(condition["field"]), json.dumps(condition["value"])]
            for key in ("require", "forbid"):
                values = condition.get(key)
                parts.append("[]string{" + ", ".join(map(json.dumps, values)) + "}" if values else "nil")
            equals = condition.get("equals")
            parts.append("map[string]any{" + ", ".join(f'{json.dumps(key)}: {json.dumps(value)}' for key, value in equals.items()) + "}" if equals else "nil")
            lines.append("{" + ", ".join(parts) + "},")
        lines.append("},")
    lines.extend(("}", "", "var normalizationProfiles = map[string]string{"))
    for digest, profile in REG["normalization_profiles"].items():
        lines.append(f'{json.dumps(digest)}: {json.dumps(profile)},')
    lines.extend(("}", "", "type kindSpec struct { body string; control bool; version int64 }",
                  "var wireKinds = map[string]kindSpec{"))
    for kind, info in REG["kinds"].items():
        lines.append(f'kind{title(kind)}: {{"{info["body"]}", {str(info["class"] == "control").lower()}, {info["body_v"]}}},')
    lines.append("}")
    for name, fields in OBJECTS.items():
        lines.extend(("", f"type {name} struct {{"))
        for key, field in fields.items():
            suffix = "" if field["required"] else ",omitempty"
            lines.append(f'{title(key)} {go_type(field["type"], field["required"])} `json:"{key}{suffix}"`')
        lines.append("}")
    return subprocess.run(["gofmt"], input=("\n".join(lines) + "\n").encode(), check=True, capture_output=True).stdout


def table(columns, rows):
    return [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
        *("| " + " | ".join(row) + " |" for row in rows),
        "",
    ]


def markdown():
    out = [START, "", "### Kinds", ""]
    out += table(("Kind", "Class", "Body version", "Body"), (
        (f"`{kind}`", info["class"], str(info["body_v"]), info["body"])
        for kind, info in REG["kinds"].items()
    ))
    for name, fields in OBJECTS.items():
        out.extend((f"### {name}", ""))
        out += table(("Member", "Type", "Required", "Meaning"), (
            (f"`{key}`", f'`{field["type"]}`', "yes" if field["required"] else "conditional or optional",
             field.get("description", ""))
            for key, field in fields.items()
        ))
    out.extend(("### Types", ""))
    out += table(("Enumeration", "Values"), (
        (f"`@{name}`", ", ".join(f"`{item}`" for item in items)) for name, items in REG["enums"].items()
    ))
    out.extend(("### Findings", ""))
    out += table(("Code", "Class"), ((f"`{code}`", cls) for code, cls in REG["findings"].items()))
    out.extend(("### Limits", ""))
    out += table(("Limit", "Value"), ((name.replace("_", " "), f"{value:,}") for name, value in LIMITS.items()))
    out.extend(("### Effect-specific producers", ""))
    out += table(("Registered call site", "Boundary", "Condition", "Group B fields"), (
        (f'`{site}`', f'`{REG["emit_sites"][site]}`', row["when"], row["fields"])
        for site, row in REG["emit_attribution"].items()
    ))
    return "\n".join((*out, END))


def render():
    for kind, info in REG["kinds"].items():
        name = info["body"]
        schema_doc = {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "title": f"Receipt v3 {kind} body v{info['body_v']}",
            **object_schema(name),
            "$defs": {dep: object_schema(dep) for dep in sorted(set(nested(name)) - {name})},
        }
        yield SDK / f"{kind}-v{info['body_v']}.schema.json", (json.dumps(schema_doc, indent=2, sort_keys=True) + "\n").encode()
    yield ROOT / "internal/receipt/v3/registry_generated.go", go_source()
    spec = SPEC.read_text(encoding="utf-8")
    before, sep, tail = spec.partition(START)
    _, close, after = tail.partition(END)
    if not sep or not close:
        raise ValueError("missing registry markers")
    yield SPEC, (before + markdown() + after).encode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    drift = []
    for file, data in render():
        if args.check:
            if not file.exists() or file.read_bytes() != data:
                drift.append(str(file.relative_to(ROOT)))
        else:
            file.write_bytes(data)
    if drift:
        parser.exit(1, "stale generated files: " + ", ".join(drift) + "\n")


if __name__ == "__main__":
    main()
